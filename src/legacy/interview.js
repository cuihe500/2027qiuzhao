  var QUANT_RE = /(\d+(\.\d+)?(%|％|倍|万|千|个|人|天|小时|分钟|分|单|篇|场|元))/;
  var REFLECT_RE = /(复盘|反思|学到|改进|优化了|如果重来|如果再来|下次|沉淀|总结出|教训)/;
  var BULLET_RE = /(首先|其次|再次|最后|第一|第二|第三|一是|二是|三是|一方面|另一方面)/;
  var LEAD_RE = /(我认为|我的结论|核心是|结论先行|整体来看|简单说|一句话|我的做法是|我的思路)/;
  // 同义词：一个概念有多种说法时，命中任一说法都算命中（避免「指标口径」写成「口径」就判没答到）
  var SYN = {
    "指标口径": ["口径", "指标定义", "统计口径", "定义一致"],
    "分渠道": ["按渠道", "渠道拆分", "渠道维度", "分渠道", "渠道对比"],
    "分版本": ["按版本", "版本对比", "分版本"],
    "分人群": ["按人群", "人群拆分", "用户分层", "分层"],
    "埋点": ["打点", "数据采集", "上报"],
    "归因": ["定位原因", "排查原因", "找到原因", "原因"],
    "AB测试": ["AB", "A/B", "实验", "对照", "灰度"],
    "修复": ["改回", "上线修复", "恢复", "修好"],
    "北极星指标": ["核心指标", "首要指标"],
    "用户调研": ["访谈", "问卷", "用户访谈"],
    "优先级": ["排期", "重要紧急", "取舍", "排序"],
    "跨部门": ["协同", "多个部门", "合作部门"],
    "量化": ["数据", "指标"],
    "复盘": ["总结", "反思", "沉淀"]
  };
  function kwHit(text, kw) {
    if (text.indexOf(kw) >= 0) return true;
    var vs = SYN[kw] || [];
    for (var i = 0; i < vs.length; i++) if (text.indexOf(vs[i]) >= 0) return true;
    return false;
  }

  // ============ 现场追问引擎：从候选人刚说出口的内容里抽取"可追问点" ============
  // 真人面试官只会追这几类：事实核验 / 方法细节 / 数据口径 / 决策取舍 / 协作过程 / 复盘迁移
  var NUM_TOKEN = /(\d+(\.\d+)?\s*(%|％|个百分点|倍|万|千|个|人|天|小时|分钟|元|次|单))/g;
  var TOOL_TOKEN = /(Excel|SQL|Python|Tableau|Power ?BI|SPSS|Axure|Figma|PRD|Jira|飞书|钉钉|企业微信|剪映|Photoshop|PS|AI|大模型|爬虫|看板|埋点|AB ?测试|AB实验)/gi;
  var ACT_TOKEN = /我(负责|主导|牵头|设计|搭建|实现|推动|组织|协调|优化|完成|跟进|参与)([\u4e00-\u9fa5A-Za-z0-9]{2,12})/g;
  var COLLAB_TOKEN = /(和|跟|与)([\u4e00-\u9fa5]{2,6})(部门|团队|同学|同事|老师|供应商|客户|技术|产品|研发|运营|设计)/g;
  var TIME_TOKEN = /(\d{4}\s*年|\d{1,2}\s*月|两周|三天|一个月|半年|上个?学期|实习期间|项目初期|上线前|上线后)/g;

  function uniqPush(arr, v, max) {
    v = (v || "").trim();
    if (!v || v.length < 2) return;
    if (arr.indexOf(v) >= 0) return;
    if (max && arr.length >= max) return;
    arr.push(v);
  }
  function extractSpans(text) {
    var out = { nums: [], tools: [], acts: [], collabs: [], times: [] };
    var m;
    NUM_TOKEN.lastIndex = 0; while ((m = NUM_TOKEN.exec(text))) uniqPush(out.nums, m[1].replace(/\s+/g, ""), 4);
    TOOL_TOKEN.lastIndex = 0; while ((m = TOOL_TOKEN.exec(text))) uniqPush(out.tools, m[1], 4);
    ACT_TOKEN.lastIndex = 0; while ((m = ACT_TOKEN.exec(text))) uniqPush(out.acts, m[1] + m[2], 3);
    COLLAB_TOKEN.lastIndex = 0; while ((m = COLLAB_TOKEN.exec(text))) uniqPush(out.collabs, m[2] + m[3], 2);
    TIME_TOKEN.lastIndex = 0; while ((m = TIME_TOKEN.exec(text))) uniqPush(out.times, m[1], 2);
    return out;
  }

  // 生成针对"这一条回答"的追问，而不是题库里的固定追问
  // 追问角度（真实面试官的追问顺序）
  function followCandidates(text) {
    var sp = extractSpans(text);
    var has = function (re) { return re.test(text); };
    var out = [];
    // ① 数据：基线 + 口径
    if (sp.nums.length) {
      if (!/(原来|之前|基线|从 ?\d)/.test(text)) out.push({ k: "数据基线", t: "你提到「" + sp.nums[0] + "」——这个数原来是多少、现在是多少？改进幅度有多大？" });
      if (!/(口径|来源|统计|后台|报表|怎么算|怎么统计|看板)/.test(text)) out.push({ k: "数据口径", t: "「" + sp.nums[0] + "」这个数字是怎么统计出来的？统计范围（分母是谁、哪个时间段）是什么？" });
    } else if (text.length > 50) {
      out.push({ k: "量化", t: "这段经历最后有具体结果吗？比如原来多少、后来变成多少，哪怕是大概区间也行。" });
    }
    // ② 方法：具体怎么做
    if (sp.acts.length) out.push({ k: "方法细节", t: "你说「" + sp.acts[0] + "」——具体分哪几步做的？中间最关键的一步是什么？" });
    else if (sp.tools.length) out.push({ k: "工具选择", t: "你用了「" + sp.tools[0] + "」，当时为什么选它？还有别的做法吗？" });
    // ③ 个人贡献
    if (sp.collabs.length || /(我们|团队|小组)/.test(text)) {
      var who = sp.collabs.length ? sp.collabs[0] : "团队";
      out.push({ k: "个人贡献", t: "你提到和「" + who + "」配合——这件事里哪些是你独立完成的？如果把你的部分拿掉，结果会怎样？" });
    }
    // ④ 决策取舍
    if (!/(因为|原因是|考虑到|对比|取舍|评估后|所以选|算了成本)/.test(text)) {
      out.push({ k: "决策取舍", t: "当时为什么用这个做法，而不是另一种？你比较过哪些方案、权衡了什么？" });
    }
    // ⑤ 复盘迁移
    if (!/(复盘|反思|总结|学到|下次|如果重来)/.test(text)) {
      out.push({ k: "复盘", t: "这件事之后你复盘出什么？后来在别的场景复用了吗？" });
    }
    // ⑥ 边界/压力（回答比较完整时往下压一层）
    if (sp.nums.length && sp.acts.length) {
      out.push({ k: "边界压力", t: "如果同样的目标只给你一半时间或一半预算，你会砍掉哪一部分？为什么是它？" });
      out.push({ k: "反事实", t: "如果当时那个关键前提不成立（比如数据口径变了/供应商不同意），你的备选方案是什么？" });
    }
    // ⑦ 质疑（只在候选人已经讲过之后出现，模拟压力面）
    if (/(很|特别|非常|巨大|显著)(大|高|好|多)的?(提升|增长|改善)|大幅提升|明显提升/.test(text)
      || (sp.nums.length && !/(口径|来源|统计|后台|报表)/.test(text))) {
      out.push({ k: "质疑", t: "你刚才说的这些，你自己信吗？给我一个能站得住的依据。" });
    }
    return out;
  }

  // 取"下一层"追问：跳过已经问过的角度
  function nextFollowUp(text, asked) {
    asked = asked || [];
    var cands = followCandidates(text);
    for (var i = 0; i < cands.length; i++) {
      if (asked.indexOf(cands[i].k) < 0) return cands[i];
    }
    return null;
  }

  // 追问层数：回答越薄追得越多（薄→3 层，压力面→3 层，其他→2 层）
  function followDepthLimit(it, r) {
    if (S && S.type === "压力面") return 3;
    if (!r) return 2;
    if (r.len < 120 || r.starCount <= 1 || (r.vague && r.vague.length)) return 3;
    return 2;
  }

  function analyze(text, q, ctx) {
    text = (text || "").trim();
    ctx = ctx || {};
    var len = text.length;
    var qkw = q.kw || [];
    var dkw = DIR_LEX[dirBase(ctx.dir)] || [];
    var jdkw = ctx.jdKw || [];
    var kws = qkw.concat(jdkw).concat(dkw);
    var hits = [], miss = [];
    kws.forEach(function (k) {
      if (kwHit(text, k)) hits.push(k); else miss.push(k);
    });
    var qHit = qkw.filter(function (k) { return kwHit(text, k); }).length;
    var dHit = dkw.filter(function (k) { return kwHit(text, k); }).length;
    var jdHit = jdkw.filter(function (k) { return kwHit(text, k); }).length;
    var jdMiss = jdkw.filter(function (k) { return !kwHit(text, k); });
    var hitRatio = qkw.length ? qHit / qkw.length : 0;

    // —— 结构逻辑（意外题用即兴判断框架，不套 STAR 模板）——
    var RE = q.w ? WILD_RE : STAR_RE;
    var star = { S: RE.S.test(text), T: RE.T.test(text), A: RE.A.test(text), R: RE.R.test(text) };
    var starCount = Object.keys(star).filter(function (k) { return star[k]; }).length;
    var hasBullet = BULLET_RE.test(text);
    var firstSentence = text.split(/[。！？\n]/)[0] || "";
    var leadFirst = LEAD_RE.test(firstSentence.slice(0, 45));
    var structure = round(clamp(64 * (starCount / 4) + (hasBullet ? 20 : 0) + (leadFirst ? 16 : 0), 0, 100));

    // —— 表达流畅 ——
    var fillers = (text.match(FILLER_RE) || []).length;
    var vagueHits = [];
    var vm;
    VAGUE_RE.lastIndex = 0;
    while ((vm = VAGUE_RE.exec(text))) { if (vagueHits.indexOf(vm[1]) < 0) vagueHits.push(vm[1]); }
    var sentences = text.split(/[。！？；\n]/).map(function (s) { return s.trim(); }).filter(function (s) { return s.length > 1; });
    var avgSent = sentences.length ? len / sentences.length : len;
    var delivery = 100, dNotes = [];
    var seconds = Number(ctx.seconds || 0);
    var cpm = 0;
    if (seconds > 3 && len > 20) {
      cpm = len / seconds * 60;
      if (cpm < 110) { delivery -= 22; dNotes.push("语速偏慢（" + round(cpm) + " 字/分），像在边想边说，练到 180–260 字/分更稳"); }
      else if (cpm < 170) { delivery -= 9; dNotes.push("语速偏慢（" + round(cpm) + " 字/分），可以再紧凑些"); }
      else if (cpm <= 290) { /* 理想区间 */ }
      else if (cpm <= 360) { delivery -= 12; dNotes.push("语速偏快（" + round(cpm) + " 字/分），机器容易判成背稿，句间留半秒停顿"); }
      else { delivery -= 26; dNotes.push("语速过快（" + round(cpm) + " 字/分），放慢到 220 字左右"); }
    } else if (seconds > 3 && len <= 20) {
      delivery -= 35;
      dNotes.push("回答太短，机器会判为内容空洞，建议每题 60–90 秒");
    }
    var fillerRate = len ? fillers / len * 100 : 0;
    if (fillers > 0) {
      var fp = clamp(fillerRate * 9, 0, 30);
      delivery -= fp;
      dNotes.push("口头禅 " + fillers + " 处（嗯/那个/然后…），目标 ≤3 处");
    }
    if (avgSent > 75) { delivery -= 10; dNotes.push("句子偏长（平均 " + round(avgSent) + " 字），拆短更容易被听懂"); }
    if (avgSent < 8 && sentences.length > 3) { delivery -= 6; dNotes.push("句子过碎，注意成段表达"); }
    delivery = round(clamp(delivery, 0, 100));

    // —— 内容匹配 ——
    var specific = 0;
    if (QUANT_RE.test(text)) specific += 9;
    if (/(项目|实习|活动|比赛|课题|社团)/.test(text)) specific += 4;
    if (ctx.company && text.indexOf(ctx.company) >= 0) specific += 2;
    var content;
    if (jdkw.length) {
      // 有 JD 时，内容分主要看 JD 关键词命中（不同岗位不互相套题）
      content = round(clamp(44 * hitRatio + 32 * (jdHit / Math.min(jdkw.length, 8)) + 12 * Math.min(dHit, 6) / 6 + specific, 0, 100));
    } else {
      content = round(clamp(52 * hitRatio + 24 * Math.min(dHit, 6) / 6 + specific, 0, 100));
    }
    if (len < 60) content = round(content * 0.6);

    // —— 深度亮点 ——
    var depth = 0;
    if (QUANT_RE.test(text)) depth += 34; else depth += 6;
    if (REFLECT_RE.test(text)) depth += 22;
    var methodHit = 0;
    ["方案", "拆解", "对比", "验证", "假设", "机制", "流程", "指标", "模型", "实验", "复盘", "优先级", "结构化"].forEach(function (w) {
      if (text.indexOf(w) >= 0) methodHit++;
    });
    depth += clamp(methodHit * 5, 0, 24);
    depth += len >= 260 ? 20 : len >= 160 ? 12 : len >= 80 ? 6 : 0;
    depth = round(clamp(depth, 0, 100));

    var total = 0.33 * content + 0.25 * structure + 0.20 * delivery + 0.22 * depth;
    if (len >= 200 && starCount >= 3) total += 5;          // 完整表达加成
    if (len >= 260 && starCount === 4 && QUANT_RE.test(text)) total += 3;  // 结构+量化都齐
    total = round(clamp(total, 1, 100));
    var grade = total >= 85 ? "A" : total >= 70 ? "B" : total >= 55 ? "C" : "D";

    // —— 建议 ——
    var advice = [];
    if (content < 70) {
      var need = (jdkw.length && jdMiss.length ? jdMiss : miss).slice(0, 4);
      advice.push((jdkw.length ? "JD 匹配偏弱：" : "内容匹配偏弱：") + "这类题的核心词还差 " + need.length + " 个"
        + (need.length ? "（" + need.join("、") + "）" : "") + "，作答时把岗位 JD 里的词主动说出来，内容分主要看这些岗位词的命中。");
    }
    if (structure < 70) {
      var names = q.w ? { S: "判断标准", T: "取舍与代价", A: "具体动作", R: "收口反思" }
                      : { S: "背景/情境", T: "任务目标", A: "你的行动", R: "量化结果" };
      var lack = Object.keys(star).filter(function (k) { return !star[k]; }).map(function (k) { return names[k]; });
      if (q.w) advice.push("这类意外题不套 STAR：先亮出你的判断标准，再说取舍和代价，最后收口给结论。" + (lack.length ? "你这次缺 " + lack.join("、") + "。" : ""));
      else advice.push("结构逻辑偏弱：缺 " + (lack.join("、") || "分点表达") + "，用「背景→任务→行动→结果」四段式，再加「首先/其次/最后」分点。");
    }
    if (delivery < 70) {
      advice.push("表达流畅偏弱：" + (dNotes[0] || "控制语速在 180–260 字/分，减少口头禅"));
    }
    if (depth < 70) {
      advice.push("深度亮点不足：补一个量化结果（提升 X%、节省 Y 小时）＋一句复盘（如果重来我会…），这两句通常是加分项。");
    }
    if (!advice.length) advice.push("这道题完成度较高：保持 STAR 结构，回答控制在限时的 70%–80%，下次可以试着加一句对业务的判断。");

    // 简历深挖题专属：个人贡献 + 数据
    if (q.types && q.types.indexOf("简历深挖") >= 0) {
      var own = (text.match(/我(负责|主导|独立|牵头|搭建|设计|推动|完成)/g) || []).length;
      var team = (text.match(/我们|团队|小组|组员/g) || []).length;
      if (own <= 0 || team > own * 1.5) {
        advice.unshift("简历深挖最关键的是「分清个人贡献」：你这段回答里「我们/团队」出现 " + team + " 次、「我负责/我主导」出现 " + own + " 次，面试官会怀疑这事是你做的。改成「我负责 X，团队负责 Y」。");
      }
      if (!QUANT_RE.test(text)) {
        advice.unshift("简历深挖必查数据：这段回答没有任何数字。准备「基线 → 结果」两个数（如从 3 小时压到 40 分钟），并说清口径来源。");
      }
    }

    var follow = [];
    // 现场追问：优先根据"你刚说出口的内容"生成，而不是题库里的固定追问（这是和模板产品最大的区别）
    follow = [];
    // 空话优先：真实面试官听到「沟通能力强」会立刻追问具体事
    if (vagueHits.length && !QUANT_RE.test(text)) {
      follow = ["你刚才说「" + vagueHits[0] + "」——具体是什么事情？你做了什么？结果是多少？"].concat(follow).slice(0, 2);
    }
    // 兜底：现场问不出新东西时，再用题库自带的深挖问题
    if (!follow.length) {
      if (total < 72 || starCount <= 2 || len < 120) follow = (q.follow || []).slice(0, 2);
      else follow = (q.follow || []).slice(0, 1);
    }
    if (vagueHits.length) {
      advice.unshift("检测到 " + vagueHits.length + " 处空话（「" + vagueHits.slice(0, 3).join("」「") + "」）：面试官听到这种词一定会追问，改成「具体做了什么 + 结果数字」。");
    }

    return {
      content: content, structure: structure, delivery: delivery, depth: depth, total: total, grade: grade,
      hits: hits, miss: miss, star: star, starCount: starCount, hasBullet: hasBullet, leadFirst: leadFirst,
      fillers: fillers, cpm: round(cpm), avgSent: round(avgSent), len: len, advice: advice, follow: follow
      , vague: vagueHits
    };
  }

