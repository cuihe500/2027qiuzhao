  async function micConnect() {
    if (MIC.on && MIC.stream) return true;
    MIC.attempts++;
    if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
      MIC.denied = true;
      micHint("当前浏览器不支持麦克风，直接用文字作答即可");
      return false;
    }
   try {
      micHint("正在连接麦克风…（浏览器会弹权限提示，请点「允许」）");
      var pReq = navigator.mediaDevices.getUserMedia({ audio: true });
      var pTimeout = new Promise(function (_, rej) {
        setTimeout(function () { rej(new Error("timeout")); }, 12000);
      });
      MIC.stream = await Promise.race([pReq, pTimeout]);
      if (destroyed) { micRelease(); return false; }
      MIC.on = true;
      micHint("麦克风已连接");
      return true;
    } catch (e) {
      MIC.denied = true;
      var why = e && e.message === "timeout" ? "未检测到麦克风设备或权限弹窗未响应" : (e && e.name) || "blocked";
      micHint("麦克风未连接（" + why + "）：点 🎙 可重试，也可以直接用文字作答");
      return false;
    }
  }
  function micRelease() {
    stopListen();
    if (MIC.stream) { try { MIC.stream.getTracks().forEach(function (t) { t.stop(); }); } catch (e) {} MIC.stream = null; }
    MIC.on = false;
  }

  function startListen() {
    if (destroyed) return;
    var SR = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (recActive) return;
    if (!SR) { micHint("当前浏览器不支持语音转写，用文字作答即可"); return; }
    recognition = new SR();
    recognition.lang = "zh-CN";
    recognition.continuous = true;
    recognition.interimResults = true;
    var base = $("aiAnswer").value || "";
    var interim = "";
    recognition.onresult = function (e) {
      var fin = "";
      for (var i = e.resultIndex; i < e.results.length; i++) {
        var t = e.results[i][0].transcript;
        if (e.results[i].isFinal) fin += t; else interim = t;
      }
      var box = $("aiAnswer");
      if (fin) { base += fin; box.value = base + interim; }
      else { box.value = base + interim; }
      box.scrollTop = box.scrollHeight;
    };
    recognition.onerror = function (ev) {
      if (ev.error !== "no-speech" && ev.error !== "aborted") micHint("语音识别出错：" + ev.error + "（可改用文字）");
    };
    recognition.onend = function () {
      recActive = false;
      var b = $("aiVoice"); if (b) b.textContent = "🎙";
      var d = $("aiRecDot"); if (d) d.classList.remove("live");
      if (MIC.on) micHint("麦克风已连接");
    };
    try { recognition.start(); } catch (e) { micHint("无法启动语音识别：" + e.message); return; }
    recActive = true;
    var vb = $("aiVoice"); if (vb) vb.textContent = "⏹";
    var dot = $("aiRecDot"); if (dot) dot.classList.add("live");
    micHint("正在听你说…");
    try {
      if (navigator.mediaDevices && navigator.mediaDevices.getUserMedia) {
        var pStream = (MIC.on && MIC.stream) ? Promise.resolve(MIC.stream) : navigator.mediaDevices.getUserMedia({ audio: true });
        pStream.then(function (stream) {
          if (destroyed) { stream.getTracks().forEach(function (track) { track.stop(); }); return; }
          MIC.stream = MIC.stream || stream; MIC.on = true;
          recChunks = [];
          try { mediaRec = new MediaRecorder(stream); } catch (e) { return; }
          mediaRec.ondataavailable = function (e) { if (e.data && e.data.size) recChunks.push(e.data); };
          mediaRec.onstop = function () {
            if (destroyed) return;
            try {
              var blob = new Blob(recChunks, { type: "audio/webm" });
              if (recUrl) URL.revokeObjectURL(recUrl);
              recUrl = URL.createObjectURL(blob);
              var pb = $("aiPlayback");
              pb.hidden = false;
              pb.onclick = function () { new Audio(recUrl).play(); };
            } catch (e) {}
          };
          mediaRec.start();
          waveStart(stream);
        }).catch(function () {});
      }
    } catch (e) {}
  }
  function stopListen() {
    if (recognition && recActive) { try { recognition.stop(); } catch (e) {} }
    recActive = false;
    if (mediaRec) { try { mediaRec.stop(); } catch (e) {} mediaRec = null; }
    var d = $("aiRecDot"); if (d) d.classList.remove("live");
    var b = $("aiVoice"); if (b) b.textContent = "🎙";
    waveStop();
    if (MIC.on) micHint("麦克风已连接");
  }
  async function toggleVoice() {
    if (recActive) { stopListen(); return; }
    if (!MIC.on) { var ok = await micConnect(); if (!ok) return; }
    startListen();
  }

