  var WAVE = { ctx: null, raf: null, analyser: null, data: null };
  function waveStart(stream) {
    try {
      WAVE.ctx = new (window.AudioContext || window.webkitAudioContext)();
      var src = WAVE.ctx.createMediaStreamSource(stream);
      WAVE.analyser = WAVE.ctx.createAnalyser();
      WAVE.analyser.fftSize = 128;
      src.connect(WAVE.analyser);
      WAVE.data = new Uint8Array(WAVE.analyser.frequencyBinCount);
      var w = $("aiWave");
      if (w) {
        w.innerHTML = new Array(30).fill("<i></i>").join("");
        w.classList.add("on");
      }
      var loop = function () {
        WAVE.raf = requestAnimationFrame(loop);
        if (!WAVE.analyser || !WAVE.data) return;
        WAVE.analyser.getByteFrequencyData(WAVE.data);
        var bars = root.querySelectorAll("#aiWave i");
        var n = bars.length || 1;
        for (var i = 0; i < n; i++) {
          var idx = Math.floor(i / n * WAVE.data.length);
          var v = WAVE.data[idx] / 255;
          bars[i].style.height = Math.max(3, Math.round(v * 22)) + "px";
        }
      };
      loop();
    } catch (e) {}
  }
  function waveStop() {
    if (WAVE.raf) { cancelAnimationFrame(WAVE.raf); WAVE.raf = null; }
    try { if (WAVE.ctx) WAVE.ctx.close(); } catch (e) {}
    WAVE.ctx = null; WAVE.analyser = null;
    var w = $("aiWave"); if (w) w.classList.remove("on");
  }

