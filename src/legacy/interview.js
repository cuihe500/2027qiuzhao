  function parseResume(text) {
    var lines = (text || "").split(/\r?\n/).map(function (l) { return l.trim(); }).filter(Boolean);
    var entries = [], cur = null;
    var timeRe = /(20\d{2}\s*[.\-\/年]\s*\d{0,2}|至今|present|20\d{2}\s*年)/i;
    var dateOnly = /^[\d\s.\-\/年月至今present~—–至到]+$/i;
    lines.forEach(function (l) {
      // 形如 "2026.08-至今" / "2025.07" 的纯时间行：并到上一条经历里，不能单独成条目
      if (dateOnly.test(l) && cur) { cur.title = (cur.title + " " + l).trim(); return; }
      var isHead = (timeRe.test(l) && !dateOnly.test(l)) || /^(项目|实习|经历|工作|科研|竞赛|社团|校园|荣誉)/.test(l) || (l.length <= 26 && /[:：]$/.test(l));
      if (isHead) {
        if (cur && (cur.points.length || cur.title)) entries.push(cur);
        // 只去掉项目符号，保留日期（否则会出现「至今 …」这种没有时间的标题）
        cur = { title: l.replace(/^[·•\-*、\s]+/, "").slice(0, 60), points: [] };
      } else if (cur) {
        cur.points.push(l.replace(/^[·•\-*\d.、\s]+/, ""));
      }
    });
    if (cur) entries.push(cur);
    if (entries.length < 2) {
      entries = (text || "").split(/\n\s*\n/).map(function (b) {
        var ls = b.split("\n").map(function (s) { return s.trim(); }).filter(Boolean);
        return ls.length ? { title: ls[0].slice(0, 60), points: ls.slice(1) } : null;
      }).filter(Boolean);
    }
    return entries.filter(function (e) {
      var t = (e.title || "").replace(/[\s.\-\/年月至今present~—–至到0-9]+/gi, "");
      return t.length >= 2;   // 只剩时间的条目直接丢掉
    }).slice(0, 8);
  }

  function resumeCheck(text) {
    var entries = parseResume(text);
    var nums = (text.match(/\d+(\.\d+)?\s*(%|％|万|千|人|天|小时|个|次|倍|元)/g) || []).length;
    var teamWords = (text.match(/参与|协助|帮忙|配合/g) || []).length;
    var ownWords = (text.match(/我负责|负责|主导|独立|牵头|搭建|设计|推动/g) || []).length;
    var issues = [];
    if (entries.length < 2) issues.push("经历条目偏少或结构不清：按「时间 + 公司/项目 + 角色」分条，每条 2–4 个要点，面试官才抓得住重点。");
    if (nums < 3) issues.push("量化太少（全文只有 " + nums + " 处数字）：简历深挖第一刀就是「数据是多少」，把「提升效率」改写成「把 X 从 A 降到 B」。");
    if (teamWords > ownWords) issues.push("「参与/协助」出现 " + teamWords + " 次，多于「负责/主导」的 " + ownWords + " 次——面试官会怀疑你的个人贡献。改写成「我负责 X，产出 Y」。");
    if (!/如果|复盘|反思|改进/.test(text)) issues.push("没有复盘痕迹：每个项目准备一句「如果重来我会…」，深挖题几乎必问。");
    if (!/为什么|原因|背景/.test(text)) issues.push("缺少决策原因：每个项目至少准备一个「为什么这么做、为什么不做另一种」的取舍理由。");
    var missing = [];
    entries.forEach(function (e) {
      var t = e.title + " " + e.points.join(" ");
      if (!/\d/.test(t)) missing.push(e.title.slice(0, 22));
    });
    return { entries: entries, issues: issues, numbers: nums, missingNumbers: missing };
  }

