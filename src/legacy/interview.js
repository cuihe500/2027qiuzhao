  function shuffle(a) {
    for (var i = a.length - 1; i > 0; i--) { var j = Math.floor(Math.random() * (i + 1)); var t = a[i]; a[i] = a[j]; a[j] = t; }
    return a;
  }
  // 裁剪题目数量时，优先保留「公司定制题」，先丢普通题
  function trimKeep(list, keep) {
    var out = list.slice();
    for (var i = out.length - 1; i >= 0 && out.length > keep; i--) {
      var q = out[i];
      if (!q.co && q.id !== "comp") out.splice(i, 1);
    }
    return out.slice(0, Math.max(keep, out.filter(function (q) { return q.co || q.id === "comp"; }).length));
  }
  // 出题：默认混入意外题 + 混搭方向 + 打乱顺序（更接近真实面试的「出其不意」）
  function pickQuestions(type, count, company, randomize) {
        function coOk() { return true; }  // 目前不做公司专属题，保留占位
    var normal = BANK.filter(function (q) {
      if (q.w) return false;
      if (q.probeOnly) return false;   // 质疑类题只在追问时出现，不能当开场题
      if (!coOk(q)) return false;
      if (q.types.indexOf(type) < 0) return false;
      var base = dirBase(dirPick);
      if (base === "综合/管培") return true;
      return q.dirs.indexOf(base) >= 0 || q.dirs.indexOf("综合/管培") >= 0;
    });
    if (normal.length < count) {
      var b2 = dirBase(dirPick);
      normal = BANK.filter(function (q) { return !q.w && coOk(q) && (q.types.indexOf(type) >= 0 || q.dirs.indexOf(b2) >= 0); });
    }
    // 面经题（内置题集 / 自己导入的）——只有勾选才参与
    var mjPool = [];
    if (mjEnabled()) {
      var coOk2 = function (q) { return !q.co || (company && company.indexOf(q.co) >= 0); };
      var base2 = dirBase(dirPick);
      mjPool = MJ_BANK.filter(function (q) {
        if (!coOk2(q)) return false;
        if (q.types.indexOf(type) < 0) return false;
        if (base2 === "综合/管培") return true;
        return q.dirs.indexOf(base2) >= 0 || q.dirs.indexOf("综合/管培") >= 0;
      }).concat(importedQuestions());
    }
    var picked = shuffle(normal.slice()).slice(0, count);
    var companyQ = company ? makeCompanyQuestion(company) : null;

    if (randomize) {
      var wildCount = count >= 8 ? 2 : 1;
      var wilds = shuffle(BANK.filter(function (q) { return q.w; })).slice(0, wildCount);
      picked = picked.slice(0, Math.max(1, count - wildCount)).concat(wilds);
      // 混搭方向：即使选了方向，也混入少量其他方向/综合题（真实面试会突然问别的）
      if (dirBase(dirPick) !== "综合/管培") {
        var mixCount = Math.max(1, Math.round(count * 0.25));
        var mix = shuffle(BANK.filter(function (q) { return !q.w && coOk(q) && q.dirs.indexOf(dirBase(dirPick)) < 0; })).slice(0, mixCount);
        picked = picked.slice(0, Math.max(1, picked.length - mixCount)).concat(mix);
      }
      // 面经题：优先安排 1–3 道（这是你最该练的真题）
      if (mjPool.length) {
        // 目标很明确时（如字节生活服务/游玩 KA），优先出对应行业的题
        var hotMj = mjPool.filter(function (q) { return /^sf/.test(q.id); });
        var pickN = Math.min(3, Math.max(1, Math.round(count / 3)));
        var mjPick = (hotMj.length && company && company.indexOf("字节") >= 0)
          ? shuffle(hotMj.slice()).slice(0, pickN)
          : shuffle(mjPool.slice()).slice(0, pickN);
        picked = picked.slice(0, Math.max(1, picked.length - mjPick.length)).concat(mjPick);
      }
      // 公司题不一定有、也不一定第一题
      if (companyQ && Math.random() < 0.6) picked = picked.concat([companyQ]);
      picked = shuffle(picked);
    } else {
      picked = shuffle(picked);
      if (companyQ) picked.unshift(companyQ);
    }
    return picked;
  }

