  function handleKeydown(event) {
    if (event.key === "Escape" && !$("aiPanel").hidden) closePanel();
  }

  function handleResize() {
    if (destroyed || !$("aiPanel").classList.contains("open") || !AV.raf) return;
    const canvas = $("aiAvatar");
    if (canvas) {
      canvas.width = 0;
      canvas.height = 0;
      avatarStart();
    }
  }

  function destroy() {
    if (destroyed) return;
    destroyed = true;
    document.removeEventListener("keydown", handleKeydown);
    window.removeEventListener("resize", handleResize);
    stopTimer();
    stopRec();
    micRelease();
    stopSpeak();
    camStop();
    avatarStop();
    pendingTimeouts.forEach((handle) => window.clearTimeout(handle));
    pendingIntervals.forEach((handle) => window.clearInterval(handle));
    pendingFrames.forEach((handle) => window.cancelAnimationFrame(handle));
    pendingTimeouts.clear();
    pendingIntervals.clear();
    pendingFrames.clear();
    if (recUrl) URL.revokeObjectURL(recUrl);
  }

