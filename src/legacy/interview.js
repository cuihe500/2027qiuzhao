  var _pdfjsLib = null;
  async function loadPdfJs() {
    if (_pdfjsLib) return _pdfjsLib;
    for (var i = 0; i < PDFJS_CDNS.length; i++) {
      try {
        var lib = await import(/* @vite-ignore */ PDFJS_CDNS[i]);
        try { lib.GlobalWorkerOptions.workerSrc = PDFJS_CDNS[i].replace("pdf.min.mjs", "pdf.worker.min.mjs"); } catch (e) {}
        _pdfjsLib = lib;
        return lib;
      } catch (e) {}
    }
    return null;
  }
  // 按 y 坐标把文字块还原成行，简历结构才留得住
  function itemsToLines(items) {
    var rows = {}, order = [];
    (items || []).forEach(function (it) {
      var s = it.str;
      if (!s) return;
      var y = Math.round((it.transform && it.transform[5]) || 0);
      if (!rows[y]) { rows[y] = []; order.push(y); }
      rows[y].push(s);
    });
    order.sort(function (a, b) { return b - a; });
    return order.map(function (y) { return rows[y].join("").replace(/\s{2,}/g, " ").trim(); }).filter(Boolean).join("\n");
  }
  async function pdfTextViaPdfJs(buf) {
    var lib = await loadPdfJs();
    if (!lib) return "";
    var doc = await lib.getDocument({ data: new Uint8Array(buf) }).promise;
    var pages = [];
    for (var i = 1; i <= doc.numPages; i++) {
      var pg = await doc.getPage(i);
      var tc = await pg.getTextContent();
      pages.push(itemsToLines(tc.items));
    }
    return pages.join("\n").trim();
  }

  async function handleResumeFile(file) {
    var name = file.name || "resume";
    var ext = (name.split(".").pop() || "").toLowerCase();
    resumeHint("正在解析 " + name + " …");
    var text = "";
    try {
      if (/^(txt|md|markdown|csv|json|rtf)$/.test(ext) || (file.type || "").indexOf("text/") === 0) {
        text = await file.text();
      } else if (ext === "docx") {
        text = stripXml(await unzipEntry(await file.arrayBuffer(), "word/document.xml"));
      } else if (ext === "pdf") {
        var pbuf = await file.arrayBuffer();
        text = await pdfText(pbuf.slice(0));                 // 先试本地轻量解析（离线可用）
        if ((text || "").replace(/\s/g, "").length < 40) {
          resumeHint("正在用 PDF 组件解析 <b>" + escAII(name) + "</b>…（首次需要联网加载约 1MB，之后走缓存）");
          try { text = await pdfTextViaPdfJs(pbuf); } catch (e2) { text = text || ""; }
        }
      } else if (/^(jpg|jpeg|png|webp|heic|bmp)$/.test(ext)) {
        resumeHint("图片简历没法在本地识别文字：用手机或系统自带的「提取文字」转成文本后，粘贴到下面即可。");
        return;
      } else {
        text = await file.text().catch(function () { return ""; });
      }
    } catch (e) {
      resumeHint("解析失败（" + (e.message || e) + "）：可以直接把简历文字粘贴到下面的输入框。");
      return;
    }
    text = (text || "").replace(/\u0000/g, "").replace(/[ \t]+\n/g, "\n").trim();
    if (text.length < 40) {
      resumeHint("这份 PDF 没解析出可复制的文字（多半是扫描件/图片版，或加密 PDF）：把简历文字粘贴到下面一样能用。");
      return;
    }
    var box = $("aiResume");
    box.value = text.slice(0, 12000);
    var mode = $("aiResumeMode");
    if (mode) mode.checked = true;
    store(RESUME_KEY, box.value);
    resumeHint("已载入 <b>" + escAII(name) + "</b>（解析出 " + text.length + " 字），已自动开启简历深挖模式。");
    try { renderResumeReport(); } catch (e) {}
  }
