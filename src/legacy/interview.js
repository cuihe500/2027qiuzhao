  // ============ 大模型主导的面试官（题目、追问、评分都由模型根据上下文生成）============
  function normQ(t) {
    return (t || "").replace(/[\s，,。.、？?！!：:；;「」“”"']/g, "").slice(0, 24);
  }
  function alreadyAsked(t) {
    if (!S || !S.askedTexts) return false;
    var n = normQ(t);
    if (!n) return true;
    var cur = (typeof S.idx === "number") ? S.idx : 0;
    return S.askedTexts.some(function (x) {
      var xn = (typeof x === "string") ? x : x.n;
      var same = xn === n || (xn.length > 8 && n.length > 8 && (xn.indexOf(n.slice(0, 8)) >= 0 || n.indexOf(xn.slice(0, 8)) >= 0));
      if (!same) return false;
      // 主问题：全程去重；追问：只在"当前题和上一题"里去重（避免同一套追问每题重复）
      if (typeof x === "string" || x.q === undefined) return true;
      return Math.abs(cur - x.qi) <= 1;
    });
  }
  function rememberAsked(t) {
    if (!S) return;
    S.askedTexts = S.askedTexts || [];
    var n = normQ(t);
    if (!n) return;
    var exists = S.askedTexts.some(function (x) { return ((typeof x === "string") ? x : x.n) === n; });
    if (!exists) S.askedTexts.push({ n: n, qi: (typeof S.idx === "number" ? S.idx : 0), main: false });
  }
  // 主问题：全程不重复（记忆为 main）
  function rememberAskedMain(t) {
    if (!S) return;
    S.askedTexts = S.askedTexts || [];
    var n = normQ(t);
    if (!n) return;
    var exists = S.askedTexts.some(function (x) { return ((typeof x === "string") ? x : x.n) === n; });
    if (!exists) S.askedTexts.push({ n: n, qi: -999, main: true });
  }

