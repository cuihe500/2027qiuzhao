  // 纯函数：从一帧像素算亮度、肤色占比与重心（便于测试）
  function frameStats(data, w, h) {
    var sum = 0, skin = 0, sx = 0, sy = 0, n = 0;
    for (var y = 0; y < h; y += 2) {
      for (var x = 0; x < w; x += 2) {
        var i = (y * w + x) * 4, r = data[i], g = data[i + 1], b = data[i + 2];
        var lum = 0.299 * r + 0.587 * g + 0.114 * b;
        sum += lum; n++;
        if (r > 95 && g > 40 && b > 20 && r > g && r > b && (Math.max(r, g, b) - Math.min(r, g, b)) > 15) {
          skin++; sx += x; sy += y;
        }
      }
    }
    var bright = n ? sum / n : 0;
    var skinRatio = n ? skin / n : 0;
    return {
      brightness: Math.round(bright),
      skinRatio: skinRatio,
      cx: skin ? (sx / skin) / w : 0.5,
      cy: skin ? (sy / skin) / h : 0.5
    };
  }
  function camTick() {
    var v = $("aiSelf"), c = $("aiCamCanvas");
    if (!v || !c || !v.videoWidth || !CAM.metrics) return;
    var ctx = c.getContext("2d", { willReadFrequently: true });
    ctx.drawImage(v, 0, 0, c.width, c.height);
    var st;
    try { st = frameStats(ctx.getImageData(0, 0, c.width, c.height).data, c.width, c.height); } catch (e) { return; }
    var m = CAM.metrics;
    m.n++;
    // 居中：肤色重心在中间 1/3 区域
    var centered = st.skinRatio > 0.03 && st.cx > 0.33 && st.cx < 0.67;
    if (centered) { m.centered++; m.offStreak = 0; } else { m.off++; m.offStreak = (m.offStreak || 0) + 1; }
    if (st.brightness < 55) { m.dark++; m.darkStreak = (m.darkStreak || 0) + 1; } else { m.darkStreak = 0; }
    // 静止：与上一帧差异过小
    if (CAM.prev) {
      var diff = 0, cnt = 0;
      for (var i = 0; i < st.brightness + 1; i++) { break; }
      diff = Math.abs(st.cx - CAM.prev.cx) + Math.abs(st.cy - CAM.prev.cy) + Math.abs(st.brightness - CAM.prev.brightness) / 255;
      if (diff < 0.012) m.still++;
      cnt++;
    }
    CAM.prev = st;
    var badge = $("aiCamState");
    if (badge) {
      var centerRate = m.n ? Math.round(m.centered / m.n * 100) : 0;
      badge.textContent = "摄像头：开启 · 居中 " + centerRate + "% · 亮度 " + st.brightness;
    }
  }
