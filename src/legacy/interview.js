  async function makeNextMainQuestion(fallbackPool) {
    if (llmReady()) {
      for (var attempt = 0; attempt < 2; attempt++) {
        try {
          var r = await llmNextQuestion(attempt);
          var q = r && r.question ? String(r.question).trim() : "";
          if (q && !alreadyAsked(q)) {
            rememberAskedMain(q);
            return {
              id: "llmq" + Math.random().toString(36).slice(2, 7),
              src: "大模型", types: ["面试"], dirs: [dirPick],
              q: q, intent: r.why || "", kw: [], points: [], pit: [], follow: []
            };
          }
        } catch (e) {
          if (attempt === 1) chatPush(bubble("ai", '<div class="ai-note">出题调用失败（' + escAII((e.message || "").slice(0, 40)) + "），已用本地题库的题目继续。</div>"));
        }
      }
    }
    // 兜底：本地题库里挑一道没问过的
    var pool = (fallbackPool || []).filter(function (q) { return !alreadyAsked(q.q); });
    if (!pool.length && typeof BANK !== "undefined") {
      pool = BANK.filter(function (q) { return !alreadyAsked(q.q); });
    }
    if (!pool.length) return null;
    var pick = shuffle(pool.slice())[0];
    rememberAskedMain(pick.q);
    return pick;
  }


