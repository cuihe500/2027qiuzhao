  async function llmChat(messages, opts) {
    var c = llmCfg();
    var base = (c.base || "https://api.deepseek.com/v1").replace(/\/$/, "");
    var body = {
      model: c.model || "deepseek-chat",
      temperature: (opts && opts.temperature) != null ? opts.temperature : 0.4,
      messages: messages
    };
    if (opts && opts.json) body.response_format = { type: "json_object" };
    var ctrl = new AbortController();
    var timer = setTimeout(function () { ctrl.abort(); }, (opts && opts.timeout) || 25000);
    try {
      var resp = await fetch(base + "/chat/completions", {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: "Bearer " + c.key },
        body: JSON.stringify(body),
        signal: ctrl.signal
      });
      var j = await resp.json();
      if (j && j.error) throw new Error(j.error.message || "接口返回错误");
      var txt = j && j.choices && j.choices[0] && j.choices[0].message ? j.choices[0].message.content : "";
      if (!txt) throw new Error("模型没有返回内容");
      return txt;
    } finally {
      clearTimeout(timer);
    }
  }
  function parseJsonLoose(txt) {
    if (!txt) return null;
    var t = txt.trim().replace(/^```json\s*/i, "").replace(/^```/, "").replace(/```$/, "").trim();
    try { return JSON.parse(t); } catch (e) {}
    var i = t.indexOf("{"), j = t.lastIndexOf("}");
    if (i >= 0 && j > i) { try { return JSON.parse(t.slice(i, j + 1)); } catch (e) {} }
    return null;
  }

