  function resumeNumberSpans(text) {
    var out = [];
    var re = /(\d+(?:\.\d+)?\s*(?:%|％|倍|万|千|人|场|次|天|小时|分钟|元|个|条|篇))/g, m;
    while ((m = re.exec(text))) {
      // 取紧邻数字的那半句（遇到标点就断开），引用起来才像人话
      var before = text.slice(Math.max(0, m.index - 24), m.index);
      var cut = Math.max(before.lastIndexOf("。"), before.lastIndexOf("，"), before.lastIndexOf(","),
        before.lastIndexOf("；"), before.lastIndexOf("\n"), before.lastIndexOf(" "));
      if (cut >= 0) before = before.slice(cut + 1);
      var frag = (before + m[1]).replace(/\s+/g, " ").trim();
      if (frag.length > 20) frag = frag.slice(-20);
      if (frag.length >= 6 && out.indexOf(frag) < 0) out.push(frag);
      if (out.length >= 6) break;
    }
    return out;
  }

